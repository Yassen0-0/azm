// Filter icons: brand/icons/*.svg → app/lib/core/widgets/filter_icon_paths.dart
// (vector data drawn by FilterIcon with the theme's colours) + composed SVGs
// for review in brand/exports/filter_icons/. Run by brand/generate.sh:
//
//   dart brand/pipeline/filter_icons.dart <repo-root> <out-root>
//
// Sources (brand/README.md → Filter icons):
// - place_*.svg, equipment_*.svg: one icon each.
// - body_front.svg, body_back.svg: the muscle-group silhouettes, one
//   element per segment with an `id`; `class="optional"` segments are drawn
//   only when highlighted. muscles.json says which view and segments each
//   muscle-group icon highlights ("*" = every segment).
//
// Contract: viewBox "0 0 64 64"; elements path/circle/ellipse/rect/line/
// polyline/polygon/g; colours ONLY the two tones below (fill and/or stroke):
// BASE (dark textTertiary) and ACCENT (dark accent), or "none". Transforms:
// translate/scale/matrix. Output is deterministic (sorted, fixed rounding).
// Pure Dart (dart:io only), so it also runs where AppKit doesn't.
import 'dart:convert';
import 'dart:io';
import 'dart:math' as math;

const base = '#88888E';
const accent = '#4D9BFF';
const viewBox = 64.0;

Never fail(String m) {
  stderr.writeln('filter_icons: $m');
  exit(1);
}

void main(List<String> args) {
  if (args.length != 2) fail('usage: filter_icons.dart <repo-root> <out-root>');
  final root = args[0], out = args[1];
  final src = Directory('$root/brand/icons');
  if (!src.existsSync()) fail('brand/icons/ is missing');

  final icons = <String, List<Shape>>{};
  final reviewSvgs = <String, String>{};

  // Standalone icons.
  final files = src.listSync().whereType<File>().map((f) => f.path.split('/').last).toList()..sort();
  for (final name in files) {
    if (!name.endsWith('.svg') || name.startsWith('body_')) continue;
    final id = name.substring(0, name.length - 4);
    if (!RegExp(r'^(place|equipment)_[a-z_]+$').hasMatch(id)) fail('$name: expected place_*.svg or equipment_*.svg');
    final shapes = parseSvg(File('${src.path}/$name').readAsStringSync(), name);
    icons[id] = [for (final s in shapes) s];
    reviewSvgs[id] = toSvg(icons[id]!);
  }

  // Muscle groups: body view + highlighted segments.
  final views = {
    for (final v in ['front', 'back']) v: parseSvg(File('${src.path}/body_$v.svg').readAsStringSync(), 'body_$v.svg'),
  };
  final muscles = jsonDecode(File('${src.path}/muscles.json').readAsStringSync()) as Map<String, dynamic>;
  for (final e in (muscles['icons'] as Map<String, dynamic>).entries) {
    final spec = e.value as Map<String, dynamic>;
    final view = views[spec['view']] ?? fail('muscles.json: ${e.key} has unknown view ${spec['view']}');
    final hi = (spec['highlight'] as List).cast<String>().toSet();
    final all = hi.contains('*');
    final ids = view.map((s) => s.id).whereType<String>().toSet();
    for (final h in hi) {
      if (h != '*' && !ids.contains(h)) fail('muscles.json: ${e.key} highlights unknown segment "$h"');
    }
    final id = 'muscle_${e.key}';
    icons[id] = [
      for (final s in view)
        if (!s.optional || hi.contains(s.id)) s.withTone(all || hi.contains(s.id) ? Tone.accent : Tone.base),
    ];
    reviewSvgs[id] = toSvg(icons[id]!);
  }

  // Dart.
  final ids = icons.keys.toList()..sort();
  final b = StringBuffer()
    ..writeln('// GENERATED by brand/generate.sh (brand/pipeline/filter_icons.dart) from brand/icons/.')
    ..writeln('// Do not edit: change the SVGs, then run brand/generate.sh. Drawn by FilterIcon.')
    ..writeln('// Shape = (tone: 0 base | 1 accent, stroke width (0 = fill), even-odd fill, path).')
    ..writeln('// Path = commands in a ${viewBox.toInt()}×${viewBox.toInt()} box: 0 x y move · 1 x y line · 2 x1 y1 x2 y2 x y cubic · 3 close.')
    ..writeln()
    ..writeln('const double filterIconViewBox = ${viewBox.toStringAsFixed(1)};')
    ..writeln()
    ..writeln('const Map<String, List<(int, double, bool, List<double>)>> filterIconData = {');
  for (final id in ids) {
    b.writeln("  '$id': [");
    for (final s in icons[id]!) {
      b.writeln('    (${s.tone.index}, ${num2(s.strokeWidth)}, ${s.evenOdd}, [${s.path.map(num2).join(', ')}]),');
    }
    b.writeln('  ],');
  }
  b.writeln('};');
  final dartFile = File('$out/app/lib/core/widgets/filter_icon_paths.dart')..createSync(recursive: true);
  dartFile.writeAsStringSync(b.toString());

  // Review SVGs (design colours, dark card background).
  final reviewDir = Directory('$out/brand/exports/filter_icons')..createSync(recursive: true);
  for (final id in ids) {
    File('${reviewDir.path}/$id.svg').writeAsStringSync(reviewSvgs[id]!);
  }
  stdout.writeln('filter_icons: ${ids.length} icons → app/lib/core/widgets/filter_icon_paths.dart + brand/exports/filter_icons/');
}

String num2(double v) {
  final r = (v * 100).round() / 100;
  if (r == r.roundToDouble()) return r.toStringAsFixed(1);
  return r.toString();
}

enum Tone { base, accent }

class Shape {
  Shape(this.id, this.tone, this.strokeWidth, this.evenOdd, this.path, {this.optional = false, this.cap = 'round'});

  final String? id;
  final Tone tone;
  final double strokeWidth; // 0 = fill
  final bool evenOdd;
  final List<double> path;
  final bool optional;
  final String cap;

  Shape withTone(Tone t) => Shape(id, t, strokeWidth, evenOdd, path, optional: optional, cap: cap);
}

String toSvg(List<Shape> shapes) {
  final b = StringBuffer('<svg viewBox="0 0 64 64" xmlns="http://www.w3.org/2000/svg">\n');
  for (final s in shapes) {
    final colour = s.tone == Tone.accent ? accent : base;
    final d = pathToD(s.path);
    if (s.strokeWidth == 0) {
      b.writeln('  <path d="$d" fill="$colour"${s.evenOdd ? ' fill-rule="evenodd"' : ''}/>');
    } else {
      b.writeln('  <path d="$d" fill="none" stroke="$colour" stroke-width="${num2(s.strokeWidth)}" '
          'stroke-linecap="round" stroke-linejoin="round"/>');
    }
  }
  b.write('</svg>\n');
  return b.toString();
}

String pathToD(List<double> p) {
  final b = StringBuffer();
  var i = 0;
  while (i < p.length) {
    final c = p[i++].toInt();
    switch (c) {
      case 0:
        b.write('M${num2(p[i++])} ${num2(p[i++])}');
      case 1:
        b.write('L${num2(p[i++])} ${num2(p[i++])}');
      case 2:
        b.write('C${[for (var k = 0; k < 6; k++) num2(p[i++])].join(' ')}');
      case 3:
        b.write('Z');
    }
  }
  return b.toString();
}

// ---- SVG parsing -------------------------------------------------------------

typedef Affine = List<double>; // a b c d e f: x' = a x + c y + e, y' = b x + d y + f

const Affine identity = [1, 0, 0, 1, 0, 0];

Affine mul(Affine m, Affine n) => [
      m[0] * n[0] + m[2] * n[1],
      m[1] * n[0] + m[3] * n[1],
      m[0] * n[2] + m[2] * n[3],
      m[1] * n[2] + m[3] * n[3],
      m[0] * n[4] + m[2] * n[5] + m[4],
      m[1] * n[4] + m[3] * n[5] + m[5],
    ];

Affine parseTransform(String? t, String where) {
  if (t == null || t.trim().isEmpty) return identity;
  var m = identity;
  for (final f in RegExp(r'(\w+)\s*\(([^)]*)\)').allMatches(t)) {
    final v = numbers(f[2]!);
    final n = switch (f[1]) {
      'translate' => <double>[1, 0, 0, 1, v[0], v.length > 1 ? v[1] : 0],
      'scale' => <double>[v[0], 0, 0, v.length > 1 ? v[1] : v[0], 0, 0],
      'matrix' when v.length == 6 => v,
      _ => fail('$where: unsupported transform "${f[0]}"'),
    };
    m = mul(m, n);
  }
  return m;
}

List<double> numbers(String s) =>
    [for (final m in RegExp(r'[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?').allMatches(s)) double.parse(m[0]!)];

Map<String, String> attrs(String s) =>
    {for (final m in RegExp(r'([\w:-]+)\s*=\s*"([^"]*)"').allMatches(s)) m[1]!: m[2]!};

List<Shape> parseSvg(String text, String name) {
  final svg = RegExp(r'<svg\b([^>]*)>').firstMatch(text) ?? fail('$name: no <svg>');
  final vb = numbers(attrs(svg[1]!)['viewBox'] ?? '');
  if (vb.length != 4 || vb[0] != 0 || vb[1] != 0 || vb[2] != viewBox || vb[3] != viewBox) {
    fail('$name: viewBox must be "0 0 64 64"');
  }
  final shapes = <Shape>[];
  final stack = <(Map<String, String>, Affine)>[({}, identity)];
  final body = text.substring(svg.end).replaceAll(RegExp(r'<!--.*?-->', dotAll: true), '');
  for (final m in RegExp(r'<(/?)([\w:-]+)([^>]*?)(/?)>').allMatches(body)) {
    final closing = m[1] == '/', tag = m[2]!, selfClosing = m[4] == '/';
    if (tag == 'svg') break;
    if (closing) {
      if (tag == 'g') stack.removeLast();
      continue;
    }
    final a = attrs(m[3]!);
    final (inherited, parentM) = stack.last;
    final style = {...inherited, ...a}..remove('id')..remove('transform')..remove('class');
    final matrix = mul(parentM, parseTransform(a['transform'], name));
    if (tag == 'g') {
      if (!selfClosing) stack.add((style, matrix));
      continue;
    }
    final where = '$name <$tag${a['id'] == null ? '' : ' id="${a['id']}"'}>';
    final path = switch (tag) {
      'path' => parsePath(a['d'] ?? fail('$where: no d'), where),
      'circle' => ellipse(dbl(a, 'cx'), dbl(a, 'cy'), dbl(a, 'r'), dbl(a, 'r')),
      'ellipse' => ellipse(dbl(a, 'cx'), dbl(a, 'cy'), dbl(a, 'rx'), dbl(a, 'ry')),
      'rect' => rect(dbl(a, 'x'), dbl(a, 'y'), dbl(a, 'width'), dbl(a, 'height'), dbl(a, 'rx', a['ry'] == null ? 0 : dbl(a, 'ry')),
          dbl(a, 'ry', a['rx'] == null ? 0 : dbl(a, 'rx'))),
      'line' => [0.0, dbl(a, 'x1'), dbl(a, 'y1'), 1.0, dbl(a, 'x2'), dbl(a, 'y2')],
      'polyline' || 'polygon' => poly(numbers(a['points'] ?? ''), close: tag == 'polygon'),
      _ => fail('$where: unsupported element'),
    };
    final t = transformPath(path, matrix);
    final scale = math.sqrt((matrix[0] * matrix[3] - matrix[1] * matrix[2]).abs());
    final optional = (a['class'] ?? '').split(' ').contains('optional');
    final fill = style['fill'] ?? (tag == 'line' || tag == 'polyline' ? 'none' : 'black');
    final stroke = style['stroke'] ?? 'none';
    Tone tone(String c) => switch (c.toUpperCase()) {
          base => Tone.base,
          accent => Tone.accent,
          _ => fail('$where: colour $c is not a filter-icon tone ($base base, $accent accent)'),
        };
    if (fill != 'none') {
      shapes.add(Shape(a['id'], tone(fill), 0, style['fill-rule'] == 'evenodd', t, optional: optional));
    }
    if (stroke != 'none') {
      final w = double.parse(style['stroke-width'] ?? '1') * scale;
      if ((style['stroke-linecap'] ?? 'round') != 'round' || (style['stroke-linejoin'] ?? 'round') != 'round') {
        fail('$where: strokes must use round caps and joins');
      }
      shapes.add(Shape(a['id'], tone(stroke), w, false, t, optional: optional));
    }
  }
  return shapes;
}

double dbl(Map<String, String> a, String k, [double? fallback]) {
  final v = a[k];
  if (v == null) return fallback ?? 0;
  return double.parse(v);
}

List<double> transformPath(List<double> p, Affine m) {
  final out = <double>[];
  var i = 0;
  (double, double) tp(double x, double y) => (m[0] * x + m[2] * y + m[4], m[1] * x + m[3] * y + m[5]);
  while (i < p.length) {
    final c = p[i++];
    out.add(c);
    final n = switch (c.toInt()) { 0 || 1 => 1, 2 => 3, _ => 0 };
    for (var k = 0; k < n; k++) {
      final (x, y) = tp(p[i++], p[i++]);
      out..add(x)..add(y);
    }
  }
  return out;
}

List<double> poly(List<double> pts, {required bool close}) =>
    [for (var i = 0; i + 1 < pts.length; i += 2) ...[i == 0 ? 0.0 : 1.0, pts[i], pts[i + 1]], if (close) 3.0];

const kappa = 0.5522847498;

List<double> ellipse(double cx, double cy, double rx, double ry) {
  final kx = rx * kappa, ky = ry * kappa;
  return [
    0, cx + rx, cy,
    2, cx + rx, cy + ky, cx + kx, cy + ry, cx, cy + ry,
    2, cx - kx, cy + ry, cx - rx, cy + ky, cx - rx, cy,
    2, cx - rx, cy - ky, cx - kx, cy - ry, cx, cy - ry,
    2, cx + kx, cy - ry, cx + rx, cy - ky, cx + rx, cy,
    3,
  ];
}

List<double> rect(double x, double y, double w, double h, double rx, double ry) {
  rx = math.min(rx, w / 2);
  ry = math.min(ry, h / 2);
  if (rx <= 0 || ry <= 0) return [0, x, y, 1, x + w, y, 1, x + w, y + h, 1, x, y + h, 3];
  final kx = rx * kappa, ky = ry * kappa;
  return [
    0, x + rx, y,
    1, x + w - rx, y,
    2, x + w - rx + kx, y, x + w, y + ry - ky, x + w, y + ry,
    1, x + w, y + h - ry,
    2, x + w, y + h - ry + ky, x + w - rx + kx, y + h, x + w - rx, y + h,
    1, x + rx, y + h,
    2, x + rx - kx, y + h, x, y + h - ry + ky, x, y + h - ry,
    1, x, y + ry,
    2, x, y + ry - ky, x + rx - kx, y, x + rx, y,
    3,
  ];
}

/// Full SVG path grammar → absolute move/line/cubic/close.
List<double> parsePath(String d, String where) {
  final tokens = RegExp(r'[MmLlHhVvCcSsQqTtAaZz]|[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?').allMatches(d).map((m) => m[0]!).toList();
  final out = <double>[];
  var i = 0;
  var cmd = '';
  double x = 0, y = 0, sx = 0, sy = 0; // current point, subpath start
  double? lcx, lcy, lqx, lqy; // last cubic / quadratic control (reflection)
  double next() {
    if (i >= tokens.length) fail('$where: truncated path');
    return double.parse(tokens[i++]);
  }

  bool isNum() => i < tokens.length && !RegExp(r'^[A-Za-z]$').hasMatch(tokens[i]);
  void cubic(double x1, double y1, double x2, double y2, double ex, double ey) {
    out.addAll([2, x1, y1, x2, y2, ex, ey]);
    lcx = x2;
    lcy = y2;
    x = ex;
    y = ey;
  }

  while (i < tokens.length) {
    if (!isNum()) cmd = tokens[i++];
    final rel = cmd == cmd.toLowerCase() && cmd != 'z' ? true : false;
    final ox = rel ? x : 0.0, oy = rel ? y : 0.0;
    final c = cmd.toUpperCase();
    final prevCubic = lcx, prevCubicY = lcy, prevQuad = lqx, prevQuadY = lqy;
    lcx = lcy = lqx = lqy = null;
    switch (c) {
      case 'M':
        x = ox + next();
        y = oy + next();
        sx = x;
        sy = y;
        out.addAll([0, x, y]);
        cmd = rel ? 'l' : 'L'; // following pairs are line-tos
      case 'L':
        x = ox + next();
        y = oy + next();
        out.addAll([1, x, y]);
      case 'H':
        x = ox + next();
        out.addAll([1, x, y]);
      case 'V':
        y = oy + next();
        out.addAll([1, x, y]);
      case 'C':
        cubic(ox + next(), oy + next(), ox + next(), oy + next(), ox + next(), oy + next());
      case 'S':
        final x1 = prevCubic == null ? x : 2 * x - prevCubic, y1 = prevCubicY == null ? y : 2 * y - prevCubicY;
        cubic(x1, y1, ox + next(), oy + next(), ox + next(), oy + next());
      case 'Q' || 'T':
        final double qx, qy;
        if (c == 'Q') {
          qx = ox + next();
          qy = oy + next();
        } else {
          qx = prevQuad == null ? x : 2 * x - prevQuad;
          qy = prevQuadY == null ? y : 2 * y - prevQuadY;
        }
        final ex = ox + next(), ey = oy + next();
        final sx0 = x, sy0 = y;
        cubic(sx0 + 2 / 3 * (qx - sx0), sy0 + 2 / 3 * (qy - sy0), ex + 2 / 3 * (qx - ex), ey + 2 / 3 * (qy - ey), ex, ey);
        lcx = lcy = null;
        lqx = qx;
        lqy = qy;
      case 'A':
        final rx = next(), ry = next(), rot = next(), large = next() != 0, sweep = next() != 0;
        final ex = ox + next(), ey = oy + next();
        for (final seg in arcToCubics(x, y, rx, ry, rot, large, sweep, ex, ey)) {
          cubic(seg[0], seg[1], seg[2], seg[3], seg[4], seg[5]);
        }
        lcx = lcy = null;
        x = ex;
        y = ey;
      case 'Z':
        out.add(3);
        x = sx;
        y = sy;
      default:
        fail('$where: bad path command "$cmd"');
    }
  }
  return out;
}

/// SVG elliptical arc (endpoint form) → cubic Béziers (≤ 90° each).
List<List<double>> arcToCubics(double x1, double y1, double rx, double ry, double phiDeg, bool large, bool sweep, double x2, double y2) {
  if (rx == 0 || ry == 0) return [[x1, y1, x2, y2, x2, y2]];
  rx = rx.abs();
  ry = ry.abs();
  final phi = phiDeg * math.pi / 180, cosP = math.cos(phi), sinP = math.sin(phi);
  final dx = (x1 - x2) / 2, dy = (y1 - y2) / 2;
  final x1p = cosP * dx + sinP * dy, y1p = -sinP * dx + cosP * dy;
  final lambda = x1p * x1p / (rx * rx) + y1p * y1p / (ry * ry);
  if (lambda > 1) {
    rx *= math.sqrt(lambda);
    ry *= math.sqrt(lambda);
  }
  final num = rx * rx * ry * ry - rx * rx * y1p * y1p - ry * ry * x1p * x1p;
  final den = rx * rx * y1p * y1p + ry * ry * x1p * x1p;
  var coef = math.sqrt(math.max(0, num / den));
  if (large == sweep) coef = -coef;
  final cxp = coef * rx * y1p / ry, cyp = -coef * ry * x1p / rx;
  final cx = cosP * cxp - sinP * cyp + (x1 + x2) / 2, cy = sinP * cxp + cosP * cyp + (y1 + y2) / 2;
  double angle(double ux, double uy, double vx, double vy) {
    final a = math.atan2(ux * vy - uy * vx, ux * vx + uy * vy);
    return a;
  }

  final t1 = angle(1, 0, (x1p - cxp) / rx, (y1p - cyp) / ry);
  var dt = angle((x1p - cxp) / rx, (y1p - cyp) / ry, (-x1p - cxp) / rx, (-y1p - cyp) / ry);
  if (!sweep && dt > 0) dt -= 2 * math.pi;
  if (sweep && dt < 0) dt += 2 * math.pi;
  final n = (dt.abs() / (math.pi / 2)).ceil().clamp(1, 8);
  final step = dt / n;
  final k = 4 / 3 * math.tan(step / 4);
  (double, double) pt(double t) =>
      (cx + rx * math.cos(t) * cosP - ry * math.sin(t) * sinP, cy + rx * math.cos(t) * sinP + ry * math.sin(t) * cosP);
  (double, double) dv(double t) =>
      (-rx * math.sin(t) * cosP - ry * math.cos(t) * sinP, -rx * math.sin(t) * sinP + ry * math.cos(t) * cosP);
  final segs = <List<double>>[];
  for (var s = 0; s < n; s++) {
    final a = t1 + s * step, b = a + step;
    final (ax, ay) = pt(a);
    final (bx, by) = pt(b);
    final (dax, day) = dv(a);
    final (dbx, dby) = dv(b);
    segs.add([ax + k * dax, ay + k * day, bx - k * dbx, by - k * dby, bx, by]);
  }
  return segs;
}
