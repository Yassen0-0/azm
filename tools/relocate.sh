#!/bin/bash
# Re-bind the Azm folder after it has been MOVED or RENAMED.
#
#   ditto OLD_ROOT NEW_ROOT        # preserves symlinks + permissions
#   NEW_ROOT/tools/relocate.sh     # can be run from any directory
#
# Safe to run any number of times, also when nothing moved.
# It never touches anything outside the folder it lives in.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
case "$ROOT" in
  *" "*) echo "ERROR: path contains spaces: $ROOT" >&2; exit 1 ;;
esac
if printf '%s' "$ROOT" | LC_ALL=C grep -q '[^ -~]'; then
  echo "ERROR: path contains non-ASCII characters: $ROOT" >&2; exit 1
fi

cd "$ROOT"
# shellcheck source=../env.sh
source ./env.sh
T="$ROOT/.tooling"
step() { printf '\n==> %s\n' "$*"; }

# Rewrite every occurrence of OLD (a previous ROOT) with ROOT in text files.
rewrite_root() { # rewrite_root OLD file...   (case-insensitive: APFS default)
  local old="$1"; shift
  [ "$old" = "$ROOT" ] && return 0
  local f
  for f in "$@"; do
    [ -f "$f" ] || continue
    OLD="$old" NEW="$ROOT" /usr/bin/perl -pi -e 's/\Q$ENV{OLD}\E/$ENV{NEW}/gi' "$f"
  done
}

step "ROOT = $ROOT"

# 1. Path-bound caches (regenerated by tools) --------------------------------------
step "Deleting path-bound caches"
rm -rf app/.dart_tool app/build app/ios/Pods \
       app/ios/Flutter/Generated.xcconfig app/ios/Flutter/flutter_export_environment.sh \
       app/android/local.properties app/android/.gradle \
       app/.flutter-plugins app/.flutter-plugins-dependencies \
       "$T/xcode-derived" "$T/home/Library/Developer/Xcode/DerivedData" \
       "$T/gradle/daemon" "$T/tmp"
mkdir -p "$T/xcode-derived" "$T/tmp"

# 2. Android emulator: AVD .ini files hold absolute paths ---------------------------
step "Fixing Android AVD paths"
AVD="$T/android-user/avd"
if [ -d "$AVD" ]; then
  for ini in "$AVD"/*.ini; do
    [ -f "$ini" ] || continue
    name="$(basename "$ini" .ini)"
    old_path="$(sed -n 's/^path=//p' "$ini" | head -1)"
    # old ROOT = old path minus the fixed suffix
    old_root="${old_path%/.tooling/android-user/avd/$name.avd}"
    if [ -n "$old_path" ] && [ "$old_root" != "$old_path" ]; then
      rewrite_root "$old_root" "$ini" "$AVD/$name.avd"/*.ini "$AVD/$name.avd"/*.txt
    fi
    # Always re-assert path= from the relative path, whatever the old value was.
    P="$AVD/$name.avd" /usr/bin/perl -pi -e 's{^path=.*}{path=$ENV{P}}' "$ini"
    # Regenerated on next boot; may still reference an unknown older location.
    rm -f "$AVD/$name.avd/hardware-qemu.ini" "$AVD/$name.avd"/*.lock
    echo "   $name -> $AVD/$name.avd"
  done
fi

# 3. CocoaPods launchers: absolute ruby path on the embedded '#!' line --------------
step "Fixing CocoaPods/RubyGems launcher scripts"
for f in "$T/gems/bin"/*; do
  [ -f "$f" ] || continue
  R="$T/ruby/bin/ruby" /usr/bin/perl -pi -e 's{^#!\S*/\.tooling/ruby/bin/ruby\b}{#!$ENV{R}}' "$f"
done
grep -l "^#!$T/ruby/bin/ruby" "$T/gems/bin"/* 2>/dev/null | sed 's/^/   ok: /' || true

# 4. Flutter: saved JDK setting + tool snapshot deps (absolute pub-cache paths) ----
step "Fixing Flutter settings"
flutter config --jdk-dir "$JAVA_HOME" 2>&1 | grep -v 'Picked up JAVA_TOOL_OPTIONS' || true
# package_config.json of flutter_tools pins absolute paths; drop the stamp so the
# tool is rebuilt (and its pub get re-run) on the next flutter command.
rm -f "$T/flutter/bin/cache/flutter_tools.stamp"

# 5. Re-fetch project dependencies ---------------------------------------------------
if [ -f app/pubspec.yaml ]; then
  step "flutter pub get"
  (cd app && flutter pub get)
  if [ -f app/ios/Podfile ]; then
    step "pod install"
    (cd app/ios && pod install)
  fi
else
  step "No app/ yet — skipping pub get / pod install"
fi

# 6. Confirm --------------------------------------------------------------------------
step "Verifying"
echo "   flutter -> $(command -v flutter)"
case "$(command -v flutter)" in "$ROOT"/*) ;; *) echo "ERROR: flutter is not inside ROOT" >&2; exit 1 ;; esac
flutter doctor -v 2>&1 | grep -v 'Picked up JAVA_TOOL_OPTIONS'
